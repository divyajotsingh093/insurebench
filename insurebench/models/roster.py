def fetch_catalogue() -> list[dict]:
    req = urllib.request.Request(MODELS_URL, headers={"User-Agent": "insurebench-roster/0.1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)["data"]


def refresh(catalogue: list[dict] | None = None, write: bool = True) -> dict:
    cat = {m["id"]: m for m in (catalogue or fetch_catalogue())}
    models, rejected = [], []
    for mid, why in CANDIDATES:
        m = cat.get(mid)
        if not m:
            rejected.append({"id": mid, "reason": "not in OpenRouter catalogue"}); continue
        if "tools" not in (m.get("supported_parameters") or []):
            rejected.append({"id": mid, "reason": "no tool-calling support"}); continue
        p = m.get("pricing", {})
        models.append({
            "id": mid, "name": m.get("name", mid), "vendor": mid.split("/")[0],
            "open_weights": bool(m.get("hugging_face_id")), "hugging_face_id": m.get("hugging_face_id") or None,
            "context_length": m.get("context_length"),
            "usd_per_1m_input": round(float(p.get("prompt", 0)) * 1e6, 4),
            "usd_per_1m_output": round(float(p.get("completion", 0)) * 1e6, 4),
            "why": why,
        })
    out = {"source": MODELS_URL, "retrieved": time.strftime("%Y-%m-%d"), "selection_basis":
           "OpenRouter monthly usage ranking (openrouter.ai/rankings) + flagship/mid/low tier per closed vendor + leading open-weight families",
           "n_models": len(models), "n_open": sum(m["open_weights"] for m in models), "models": models, "rejected": rejected}
    if write:
        import yaml
        ROSTER_PATH.write_text("# Generated by `python -m insurebench roster refresh`. Do not edit by hand; edit CANDIDATES in roster.py.\n"
                               + yaml.safe_dump(out, sort_keys=False, width=140))
    return out


def load() -> dict:
    if not ROSTER_PATH.exists():
        return {"models": []}
    import yaml
    return yaml.safe_load(ROSTER_PATH.read_text())


def validate(r: dict | None = None) -> list[str]:
    r = r or load()
    errs = []
    ids = [m["id"] for m in r.get("models", [])]
    if len(ids) != 30:
        errs.append(f"roster has {len(ids)} models, expected 30")
    if len(set(ids)) != len(ids):
        errs.append("duplicate ids")
    for m in r.get("models", []):
        if m["usd_per_1m_input"] < 0 or m["usd_per_1m_output"] < 0:
            errs.append(f"{m['id']}: negative price")
    if r.get("models") and not (0 < r["n_open"] < len(ids)):
        errs.append("roster must mix open and closed models")
    return errs


_PRICING: dict | None = None


def pricing() -> dict[str, tuple[float, float]]:
    global _PRICING
    if _PRICING is None:
        _PRICING = {m["id"]: (m["usd_per_1m_input"], m["usd_per_1m_output"]) for m in load().get("models", [])}
    return _PRICING
